      <h1 id="privacy-title">Privacy Policy</h1>
      <p class="legal-updated">Last updated: October 29, 2026</p>
      <p>This policy explains how Role Glide (“we”, “us”) collects, uses and protects your personal information when you use this website and submit our form. We handle personal information in line with Canada’s Personal Information Protection and Electronic Documents Act (PIPEDA) and any applicable provincial privacy law.</p>

      <h2>1. What we collect</h2>
      <p>When you submit the form on this website, we collect:</p>
      <ul>
        <li>your name</li>
        <li>your email address</li>
        <li>your phone number (WhatsApp)</li>
        <li>your province or territory</li>
      </ul>
      <p>If we get in touch about a role, we may ask you for more information, such as your skills and availability. We only ask for what we need.</p>

      <h2>2. Why we collect it</h2>
      <ul>
        <li>to review your information and contact you about work opportunities that may suit you</li>
        <li>to share your details with companies that are hiring, but only for a role you have agreed to be considered for</li>
        <li>to answer your questions and keep records of our communication with you</li>
        <li>to improve this website and measure how our advertising performs</li>
      </ul>

      <h2>3. Your consent</h2>
      <p>By submitting the form, you agree to us collecting, using and sharing your information as described in this policy. You can withdraw your consent at any time by contacting us, subject to legal or contractual limits. If you withdraw, we may not be able to consider you for roles.</p>

      <h2>4. Who we share it with</h2>
      <p>We do not sell your personal information. We may share it with:</p>
      <ul>
        <li>companies that are hiring, as described above</li>
        <li>service providers who help us run this website and store or process data on our behalf, such as hosting, email and form tools.</li>
        <li>authorities, where the law requires it</li>
      </ul>

      <h2>5. How long we keep it</h2>
      <p>We keep your information for 90 days from your last contact with us, and then delete or anonymise it unless the law requires us to keep it longer.</p>

      <h2>6. How we protect it</h2>
      <p>We use reasonable physical, technical and organisational safeguards to protect your information against loss, theft and unauthorised access. No method of transmission or storage is completely secure, so we cannot guarantee absolute security.</p>

      <h2>7. Your rights</h2>
      <p>You can ask us to:</p>
      <ul>
        <li>tell you what personal information we hold about you</li>
        <li>correct information that is wrong or out of date</li>
        <li>delete your information</li>
        <li>stop contacting you</li>
      </ul>
      <p>Contact us using the details below. We will respond within a reasonable time and may need to confirm your identity first. If you are not satisfied with our response, you can contact the Office of the Privacy Commissioner of Canada or your provincial privacy regulator.</p>

      <h2>8. Marketing emails</h2>
      <p>We only send you messages about opportunities and our service. Every marketing message will let you unsubscribe, in line with Canada’s Anti-Spam Legislation (CASL).</p>

      <h2>9. Cookies</h2>
